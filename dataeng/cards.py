"""Dataset cards: render a markdown dataset card from a pipeline run manifest.

A card is the contract between the people who built a dataset and everyone
who will train on or evaluate with it: where it came from, what pipeline
(and which versions) produced it, its statistics, and its known limitations.
"""
from __future__ import annotations

REQUIRED_KEYS = ("name", "version", "source", "pipeline_steps", "stats")


def _fmt_stats(stats: dict) -> str:
    lines = []
    for key in sorted(stats):
        value = stats[key]
        if isinstance(value, dict):
            inner = ", ".join(f"{k}: {v}" for k, v in sorted(value.items()))
            lines.append(f"- **{key}**: {inner}")
        else:
            lines.append(f"- **{key}**: {value}")
    return "\n".join(lines) if lines else "_none recorded_"


def _fmt_steps(steps: list) -> str:
    lines = []
    for i, step in enumerate(steps, 1):
        name = step.get("name", f"step-{i}")
        version = step.get("version", "unspecified")
        params = step.get("params", {})
        param_str = (
            ", ".join(f"{k}={v}" for k, v in sorted(params.items()))
            if params else "defaults"
        )
        lines.append(f"{i}. **{name}** (v{version}) — {param_str}")
    return "\n".join(lines) if lines else "_no steps recorded_"


def build_dataset_card(manifest: dict) -> str:
    """Render a markdown dataset card. Raises ValueError listing any missing
    required keys: name, version, source, pipeline_steps, stats."""
    missing = [k for k in REQUIRED_KEYS if k not in manifest]
    if missing:
        raise ValueError(f"manifest missing required keys: {', '.join(missing)}")

    limitations = manifest.get("limitations", [])
    lim_md = (
        "\n".join(f"- {lim}" for lim in limitations)
        if limitations else "_none declared_"
    )

    return f"""# Dataset Card: {manifest['name']}

**Version:** {manifest['version']}
**Source:** {manifest['source']}
**Created:** {manifest.get('created', 'unspecified')}
**License / usage:** {manifest.get('license', 'unspecified — confirm before use')}
**Contact:** {manifest.get('contact', 'unspecified')}

## Pipeline
{_fmt_steps(manifest['pipeline_steps'])}

## Statistics
{_fmt_stats(manifest['stats'])}

## Known limitations
{lim_md}

## Intended use
{manifest.get('intended_use', 'Training and evaluation of language models. '
'Validate on your own evals before production use.')}

---
*Generated by Jagadish-dataset-engineering. All data in this project is synthetic.*
"""
